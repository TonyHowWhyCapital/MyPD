import '../Math';
import { encode } from './xml';
import { applyDataSourceToPdm } from './write';

// Target label per project database type. The shortcut names the DBMS definition
// the modeling tool should load; without one the user picks the DBMS on opening.
const targets = {
  sqlserver: ['Microsoft SQL Server 2017', 'MSSQLSRV2017', 'E8045424-6406-4D7B-924F-B041C2BA2DC5'],
  postgresql: ['PostgreSQL 9.x', 'PGSQL9', '83063C86-4E0A-4954-BF00-620C0D0F02D8'],
  oracle: ['ORACLE Version 11g', 'ORA11GR1', 'BAE632F3-AC04-4059-9893-259ABA89351C'],
  mysql: ['MySQL 5.0'],
};
const DBMS_CLASS = '4BA9F647-DAB1-11D1-9944-006097355D9B';
const MODEL_TYPE = '{CDE44E21-9669-11D1-9914-006097355D9B}';

const GRID_COLUMNS = 4;
const SYMBOL_WIDTH = 12000;
const SYMBOL_GAP = 3000;
const symbolHeight = columns => 2200 + 420 * Math.max(columns, 1);

const guid = () => Math.uuid().toUpperCase();
const hasValue = v => v !== '' && v !== undefined && v !== null;

const stamp = (now, user) => [
  `<a:CreationDate>${now}</a:CreationDate>`,
  `<a:Creator>${encode(user)}</a:Creator>`,
  `<a:ModificationDate>${now}</a:ModificationDate>`,
  `<a:Modifier>${encode(user)}</a:Modifier>`,
];

const skeleton = ({ name, code, target, now, user }) => {
  const modelId = guid();
  const [label, dbmsCode, dbmsId] = target;
  const dbms = dbmsId ? [
    '<c:DBMS>',
    '<o:Shortcut Id="o3">',
    `<a:ObjectID>${guid()}</a:ObjectID>`,
    `<a:Name>${encode(label)}</a:Name>`,
    `<a:Code>${dbmsCode}</a:Code>`,
    ...stamp(now, user),
    '<a:TargetStereotype/>',
    `<a:TargetID>${dbmsId}</a:TargetID>`,
    `<a:TargetClassID>${DBMS_CLASS}</a:TargetClassID>`,
    '</o:Shortcut>',
    '</c:DBMS>',
  ] : [];
  return [
    '<?xml version="1.0" encoding="UTF-8"?>',
    `<?PowerDesigner AppLocale="UTF16" ID="{${modelId}}" Label="" LastModificationDate="${now}" Name="${encode(name).replace(/"/g, '&quot;')}" Objects="0" Symbols="0" Target="${encode(label).replace(/"/g, '&quot;')}" Type="${MODEL_TYPE}" signature="PDM_DATA_MODEL_XML" version="16.6.4.5517"?>`,
    '<!-- do not edit this file -->',
    '',
    '<Model xmlns:a="attribute" xmlns:c="collection" xmlns:o="object">',
    '',
    '<o:RootObject Id="o1">',
    '<a:SessionID>00000000-0000-0000-0000-000000000000</a:SessionID>',
    '<c:Children>',
    '<o:Model Id="o2">',
    `<a:ObjectID>${modelId}</a:ObjectID>`,
    `<a:Name>${encode(name)}</a:Name>`,
    `<a:Code>${encode(code)}</a:Code>`,
    ...stamp(now, user),
    ...dbms,
    '<c:PhysicalDiagrams>',
    '<o:PhysicalDiagram Id="o4">',
    `<a:ObjectID>${guid()}</a:ObjectID>`,
    `<a:Name>${encode(name)}</a:Name>`,
    `<a:Code>${encode(code)}</a:Code>`,
    ...stamp(now, user),
    '</o:PhysicalDiagram>',
    '</c:PhysicalDiagrams>',
    '<c:DefaultDiagram>',
    '<o:PhysicalDiagram Ref="o4"/>',
    '</c:DefaultDiagram>',
    '</o:Model>',
    '</c:Children>',
    '</o:RootObject>',
    '',
    '</Model>',
    '',
  ].join('\n');
};

const effectiveType = (field, dataSource, dbId) => {
  const mappings = dataSource.dataTypeMapping?.mappings || [];
  const domain = field.domain && (dataSource.domains || []).find(d => d.id === field.domain);
  const mapping = mappings.find(m => m.id === (field.baseType || domain?.applyFor));
  return {
    type: mapping?.[dbId] || field.type || '',
    len: domain ? domain.len : field.len,
    scale: domain ? domain.scale : field.scale,
  };
};

// The file stores each column's concrete type for the target database, so
// project-side domains and type mappings are resolved before writing.
const flatten = (entities, dataSource, dbId, kept) => entities.map((entity) => {
  const fields = (entity.fields || []).map((field) => {
    const { type, len, scale } = effectiveType(field, dataSource, dbId);
    return {
      ...field,
      id: guid(),
      sourceId: field.id,
      type,
      len: hasValue(len) ? len : '',
      scale: hasValue(len) && hasValue(scale) ? scale : '',
      domain: kept.has(field.domain) ? field.domain : '',
      baseType: '',
    };
  });
  const fieldId = (key) => {
    const lower = `${key || ''}`.toLowerCase();
    const found = fields.find(f => f.sourceId === key) || fields.find(f => f.defKey.toLowerCase() === lower);
    return found ? found.id : '';
  };
  return {
    ...entity,
    id: guid(),
    fields,
    indexes: (entity.indexes || []).map(index => ({
      ...index,
      id: guid(),
      fields: (index.fields || []).map(f => ({ ...f, fieldDefKey: fieldId(f.fieldDefKey) })),
    })),
  };
});

// Lays the tables out on a grid in the default diagram so they are visible on opening.
const addSymbols = (xml, entities) => {
  const tableIds = (xml.match(/<o:Table Id="o\d+">/g) || []).map(m => m.slice(13, -2));
  let nextId = Math.max(...(xml.match(/ Id="o\d+"/g) || []).map(m => parseInt(m.slice(6, -1), 10)));
  let top = 0;
  let rowHeight = 0;
  const symbols = tableIds.map((id, i) => {
    const column = i % GRID_COLUMNS;
    if (column === 0) {
      top -= rowHeight ? rowHeight + SYMBOL_GAP : 0;
      rowHeight = 0;
    }
    const height = symbolHeight((entities[i].fields || []).length);
    rowHeight = Math.max(rowHeight, height);
    const left = column * (SYMBOL_WIDTH + SYMBOL_GAP);
    nextId += 1;
    return [
      `<o:TableSymbol Id="o${nextId}">`,
      `<a:Rect>((${left},${top - height}), (${left + SYMBOL_WIDTH},${top}))</a:Rect>`,
      '<c:Object>',
      `<o:Table Ref="${id}"/>`,
      '</c:Object>',
      '</o:TableSymbol>',
    ].join('\n');
  });
  if (symbols.length === 0) {
    return xml;
  }
  return xml
    .replace('</o:PhysicalDiagram>\n</c:PhysicalDiagrams>',
      `<c:Symbols>\n${symbols.join('\n')}\n</c:Symbols>\n</o:PhysicalDiagram>\n</c:PhysicalDiagrams>`)
    .replace(' Symbols="0" ', ` Symbols="${symbols.length}" `)
    .replace(' Objects="0" ', ` Objects="${(xml.match(/<a:ObjectID>/g) || []).length}" `);
};

// Builds a new model file from tables. `entityIds` limits it to chosen tables.
// The reverse engine hands a database remark over as the display name. A PDM keeps
// remarks in Comment, so tables and columns without a comment get the remark there.
export const remarksAsComments = (entities) => {
  const fill = o => (o.comment || !o.defName ? o : { ...o, comment: o.defName });
  return (entities || []).map(e => ({ ...fill(e), fields: (e.fields || []).map(fill) }));
};

// `domainIds` names the domains to carry into the file with their column links. All
// other columns are written with their concrete type only.
export const createPdm = (dataSource, {
  name, dbId, entityIds, domainIds = [], now, user = 'MyPD',
} = {}) => {
  const supports = dataSource.profile?.dataTypeSupports || [];
  const db = supports.find(s => s.id === dbId) || supports.find(s => s.id === dataSource.profile?.default?.db);
  const chosen = (dataSource.entities || []).filter(e => !entityIds || entityIds.includes(e.id));
  if (chosen.length === 0) {
    throw new Error('No tables to write');
  }
  const modelName = name || dataSource.name || 'Model';
  const time = now || Math.floor(Date.now() / 1000);
  const kept = new Set(domainIds);
  const entities = flatten(chosen, dataSource, db?.id, kept);
  const xml = applyDataSourceToPdm(skeleton({
    name: modelName,
    code: modelName.replace(/[^\w]+/g, '_'),
    target: targets[`${db?.defKey || ''}`.toLowerCase()] || [db?.defKey || 'ANSI Level 2'],
    now: time,
    user,
  }), {
    ...dataSource,
    entities,
    domains: (dataSource.domains || []).filter(d => kept.has(d.id)),
  }, { now: time, user });
  return addSymbols(xml, entities);
};
